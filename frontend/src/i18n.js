let lang = localStorage.getItem('lang') || 'sr'

export function getLang() {
  return lang
}

// A full reload keeps this simple: every t() call across the app - and
// every piece of Serbian-only product data - re-renders consistently
// instead of needing a shared reactive language store.
export function setLang(newLang) {
  localStorage.setItem('lang', newLang)
  window.location.reload()
}

export function t(key) {
  return strings[lang][key] ?? strings.sr[key] ?? key
}
